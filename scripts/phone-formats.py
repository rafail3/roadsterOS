"""Writes core-car's phone number formats from Google libphonenumber's metadata.

    python -I scripts/phone-formats.py <PhoneNumberMetadata.xml>

The XML is resources/PhoneNumberMetadata.xml of github.com/google/libphonenumber (Apache 2.0). Kept per region:
the country calling code, the national prefix, the international prefix, whether it is the main region of its code,
and each number format: its pattern, its national and international layout, how the national prefix joins the first
group, and its leading-digit patterns. Writes core-car/src/commonMain/kotlin/ro/rdstr/car/PhoneFormats.kt.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "core-car", "src", "commonMain", "kotlin",
                   "ro", "rdstr", "car", "PhoneFormats.kt")


def clean(text):
    return re.sub(r"\s+", "", text or "")


def enc(text):
    # "$" would start a Kotlin string template; the data uses "@" in its place
    assert "@" not in text and "\t" not in text and "\n" not in text, text
    return text.replace("$", "@")


def main():
    root = ET.parse(sys.argv[1]).getroot()
    lines = []
    for t in root.iter("territory"):
        region, code = t.get("id"), t.get("countryCode")
        if region == "001":
            continue
        rule = t.get("nationalPrefixFormattingRule", "")
        formats = []
        available = t.find("availableFormats")
        for f in (available.findall("numberFormat") if available is not None else []):
            intl = f.find("intlFormat")
            fields = [
                clean(f.get("pattern")),
                (f.findtext("format") or "").strip(),
                (intl.text or "").strip() if intl is not None else "",
                f.get("nationalPrefixFormattingRule", rule),
                "^".join(clean(ld.text) for ld in f.findall("leadingDigits")),
            ]
            formats.append("\t".join(enc(x) for x in fields))
        head = "\t".join(enc(x) for x in [region, code, t.get("nationalPrefix", ""), t.get("internationalPrefix", ""),
                                          "1" if t.get("mainCountryForCode") == "true" else "0"])
        lines.append("\n".join([head] + formats))
    body = ",\n".join('        """' + line + '"""' for line in lines)
    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write(f"""package ro.rdstr.car

// Generated by scripts/phone-formats.py from Google libphonenumber's PhoneNumberMetadata.xml (Apache 2.0). Do not
// edit by hand. One string per region: a head line (region, calling code, national prefix, international prefix,
// main region of its code) and one line per number format (pattern, format, international format, national prefix
// rule, leading digits joined by ^); fields split by tabs, "@" stands for "$".
internal object PhoneFormats {{
    val REGIONS = listOf(
{body},
    )
}}
""")
    print(f"{len(lines)} regions, {os.path.getsize(OUT) // 1024} KB")


if __name__ == "__main__":
    main()
