package ro.rdstr.gradle.display

/** Writes the generated Kotlin sources of `core-ui`: the token classes and the icon table. */
object KotlinWriter {
    private const val HEADER = "// Generated by rdstr.display from emulator/styles. Do not edit: change the CSS and build again."

    fun tokens(pkg: String, classes: List<TokenClass>): String = buildString {
        appendLine(HEADER)
        appendLine("@file:Suppress(\"unused\", \"SpellCheckingInspection\")")
        appendLine()
        appendLine("package $pkg")
        for (c in classes) {
            appendLine()
            val where = c.component.ifEmpty { "the screen" }.let { if (c.component.isEmpty()) it else "`.${it.replace(" ", " .")}`" }
            appendLine("/** Custom properties of $where, per theme and design; lengths in canvas px (dp in our app). */")
            appendLine("class ${c.name}(")
            for (f in c.fields) {
                appendLine("    /** `${f.property}` (${f.files.joinToString()}) */")
                appendLine("    val ${f.name}: ${f.type}${if (f.nullable) "?" else ""},")
            }
            appendLine(") {")
            appendLine("    companion object {")
            val written = mutableListOf<Pair<String, Map<String, TokenValue?>>>()
            for ((instance, values) in c.instances) {
                val same = written.firstOrNull { it.second == values }
                if (same != null) { appendLine("        val $instance get() = ${same.first}"); continue }
                written += instance to values
                appendLine("        val $instance = ${c.name}(")
                for (f in c.fields) appendLine("            ${f.name} = ${values[f.property]?.kotlin() ?: "null"},")
                appendLine("        )")
            }
            val keys = c.instances.keys
            when {
                keys.containsAll(listOf("DARK", "LIGHT", "GLASSY_DARK", "GLASSY_LIGHT")) ->
                    appendLine("        fun of(light: Boolean, glassy: Boolean) = if (glassy) { if (light) GLASSY_LIGHT else GLASSY_DARK } else { if (light) LIGHT else DARK }")
                keys == setOf("GLASSY_DARK", "GLASSY_LIGHT") -> appendLine("        fun of(light: Boolean) = if (light) GLASSY_LIGHT else GLASSY_DARK")
                else -> throw DisplayBuildException("${c.name}: instances ${keys.joinToString()} have no lookup")
            }
            appendLine("    }")
            appendLine("}")
        }
    }

    fun icons(pkg: String, rPackage: String, icons: List<IconClass>, files: List<String>): String = buildString {
        appendLine(HEADER)
        appendLine()
        appendLine("package $pkg")
        appendLine()
        appendLine("import $rPackage.R")
        appendLine()
        appendLine("/** The emulator's icons as VectorDrawables, by file and by the CSS class the components use (`icon i-…`). */")
        appendLine("object Icons {")
        for (f in files.sorted()) appendLine("    val ${constant(f)} get() = R.drawable.${drawable(f)}")
        appendLine()
        appendLine("    /** CSS class → drawable. */")
        appendLine("    val byClass: Map<String, Int> get() = mapOf(")
        for (i in icons.sortedBy { it.cssClass }) appendLine("        \"${i.cssClass}\" to R.drawable.${drawable(i.file.removeSuffix(".svg"))},")
        appendLine("    )")
        appendLine("}")
    }

    fun fonts(pkg: String, rPackage: String, faces: List<DisplayBuild.Face>): String = buildString {
        appendLine(HEADER)
        appendLine()
        appendLine("package $pkg")
        appendLine()
        appendLine("import $rPackage.R")
        appendLine()
        appendLine("/** The screen's font families, the same files the emulator loads, variable on weight. */")
        appendLine("object Fonts {")
        for (f in faces) {
            appendLine("    /** \"${f.family}\" from emulator/public/fonts/${f.file}, weights ${f.weights.first}-${f.weights.last} */")
            appendLine("    val ${f.family.uppercase().replace(Regex("[^A-Z0-9]"), "_")} get() = R.font.${f.resource}")
        }
        appendLine()
        appendLine("    /** CSS family name to font resource. */")
        appendLine("    val byFamily: Map<String, Int> get() = mapOf(${faces.joinToString { "\"${it.family}\" to R.font.${it.resource}" }})")
        appendLine()
        appendLine("    /** CSS family name to the weights its file covers. */")
        appendLine("    val weights: Map<String, IntRange> = mapOf(${faces.joinToString { "\"${it.family}\" to ${it.weights.first}..${it.weights.last}" }})")
        appendLine("}")
    }

    fun drawable(stem: String) = "rdstr_icon_" + stem.replace('-', '_')
    private fun constant(stem: String) = stem.uppercase().replace('-', '_')
}
