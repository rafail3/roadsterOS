package ro.rdstr.gradle.display

import org.w3c.dom.Element
import javax.xml.parsers.DocumentBuilderFactory
import kotlin.math.abs
import kotlin.math.hypot

/**
 * The emulator's icons (one-colour SVG drawn through a CSS mask) as Android VectorDrawables: the same paths in the same
 * viewport, every ink white so the view tints it as `currentColor` does. Shapes become paths; a mask of strokes cut out
 * of the full viewport becomes a clip path with the strokes' outlines wound the other way. Anything else stops the build.
 */
object Svg {
    private const val INK = "#FFFFFFFF"
    private val inkColors = setOf("currentcolor", "#000", "#000000", "black")

    private data class Paint(val fill: String?, val stroke: String?, val width: Double, val cap: String, val join: String, val opacity: Double)

    fun toVector(name: String, svgText: String, sizeDp: Int = 28): String {
        val factory = DocumentBuilderFactory.newInstance().apply {
            isNamespaceAware = false
            setFeature("http://apache.org/xml/features/disallow-doctype-decl", true)
        }
        val root = factory.newDocumentBuilder().parse(svgText.byteInputStream()).documentElement
        val view = (root.getAttribute("viewBox").ifEmpty { throw DisplayBuildException("$name: no viewBox") })
            .trim().split(Regex("[ ,]+")).map { it.toDouble() }
        if (view[0] != 0.0 || view[1] != 0.0) throw DisplayBuildException("$name: viewBox must start at 0 0")
        val masks = mutableMapOf<String, String>()
        val body = StringBuilder()
        val rootPaint = paint(name, root, Paint("ink", null, 1.0, "butt", "miter", 1.0))

        fun walk(el: Element, inherited: Paint, indent: String) {
            for (i in 0 until el.childNodes.length) {
                val child = el.childNodes.item(i) as? Element ?: continue
                when (child.tagName) {
                    "defs" -> for (k in 0 until child.childNodes.length) {
                        val m = child.childNodes.item(k) as? Element ?: continue
                        if (m.tagName != "mask") throw DisplayBuildException("$name: <defs> may hold only <mask>")
                        masks[m.getAttribute("id")] = maskClip(name, m, view[2], view[3])
                    }
                    "g" -> {
                        if (child.hasAttribute("transform") || child.hasAttribute("mask")) throw DisplayBuildException("$name: <g> with transform or mask")
                        walk(child, paint(name, child, inherited), indent)
                    }
                    "title", "desc" -> Unit
                    else -> {
                        val p = paint(name, child, inherited)
                        val data = pathData(name, child)
                        val mask = child.getAttribute("mask").takeIf { it.isNotEmpty() }
                        if (mask != null) {
                            val id = Regex("""url\(#(.+)\)""").find(mask)?.groupValues?.get(1) ?: throw DisplayBuildException("$name: mask $mask")
                            val clip = masks[id] ?: throw DisplayBuildException("$name: mask #$id is used before it is defined")
                            body.append("$indent<group>\n$indent    <clip-path android:pathData=\"$clip\" />\n")
                            body.append(path(data, p, "$indent    "))
                            body.append("$indent</group>\n")
                        } else body.append(path(data, p, indent))
                    }
                }
            }
        }
        walk(root, rootPaint, "    ")
        return buildString {
            append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
            append("<!-- Generated by rdstr.display from emulator/public/icons/$name.svg. Do not edit. -->\n")
            append("<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n")
            append("    android:width=\"${sizeDp}dp\"\n    android:height=\"${sizeDp}dp\"\n")
            append("    android:viewportWidth=\"${fmt(view[2])}\"\n    android:viewportHeight=\"${fmt(view[3])}\">\n")
            append(body)
            append("</vector>\n")
        }
    }

    private fun path(data: String, p: Paint, indent: String) = buildString {
        append("$indent<path\n$indent    android:pathData=\"$data\"")
        if (p.fill != null) append("\n$indent    android:fillColor=\"$INK\"")
        if (p.stroke != null) {
            append("\n$indent    android:strokeColor=\"$INK\"\n$indent    android:strokeWidth=\"${fmt(p.width)}\"")
            if (p.cap != "butt") append("\n$indent    android:strokeLineCap=\"${p.cap}\"")
            if (p.join != "miter") append("\n$indent    android:strokeLineJoin=\"${p.join}\"")
        }
        if (p.opacity != 1.0) {
            if (p.fill != null) append("\n$indent    android:fillAlpha=\"${fmt(p.opacity)}\"")
            if (p.stroke != null) append("\n$indent    android:strokeAlpha=\"${fmt(p.opacity)}\"")
        }
        append(" />\n")
    }

    private fun paint(name: String, el: Element, inherited: Paint): Paint {
        fun ink(attr: String, current: String?): String? {
            if (!el.hasAttribute(attr)) return current
            val v = el.getAttribute(attr).trim().lowercase()
            return when {
                v == "none" -> null
                v in inkColors -> "ink"
                else -> throw DisplayBuildException("$name: $attr=\"$v\"; icons are one colour, tinted by the view")
            }
        }
        if (el.hasAttribute("style") || el.hasAttribute("transform")) throw DisplayBuildException("$name: style or transform attribute on <${el.tagName}>")
        return Paint(
            fill = ink("fill", inherited.fill),
            stroke = ink("stroke", inherited.stroke),
            width = el.getAttribute("stroke-width").toDoubleOrNull() ?: inherited.width,
            cap = el.getAttribute("stroke-linecap").ifEmpty { inherited.cap },
            join = el.getAttribute("stroke-linejoin").ifEmpty { inherited.join },
            opacity = inherited.opacity * (el.getAttribute("opacity").toDoubleOrNull() ?: 1.0),
        )
    }

    private fun d(el: Element, a: String) = el.getAttribute(a).ifEmpty { "0" }.toDouble()

    fun pathData(name: String, el: Element): String = when (el.tagName) {
        "path" -> el.getAttribute("d").trim()
        "circle" -> circle(d(el, "cx"), d(el, "cy"), d(el, "r"))
        "ellipse" -> ellipse(d(el, "cx"), d(el, "cy"), d(el, "rx"), d(el, "ry"))
        "rect" -> rect(d(el, "x"), d(el, "y"), d(el, "width"), d(el, "height"),
            el.getAttribute("rx").ifEmpty { el.getAttribute("ry") }.ifEmpty { "0" }.toDouble())
        "line" -> "M${fmt(d(el, "x1"))},${fmt(d(el, "y1"))} L${fmt(d(el, "x2"))},${fmt(d(el, "y2"))}"
        "polyline", "polygon" -> {
            val n = el.getAttribute("points").trim().split(Regex("[ ,]+")).map { it.toDouble() }.chunked(2)
            n.mapIndexed { i, p -> (if (i == 0) "M" else "L") + "${fmt(p[0])},${fmt(p[1])}" }.joinToString(" ") +
                if (el.tagName == "polygon") " Z" else ""
        }
        else -> throw DisplayBuildException("$name: <${el.tagName}> is not handled")
    }

    fun circle(cx: Double, cy: Double, r: Double) = ellipse(cx, cy, r, r)

    private fun ellipse(cx: Double, cy: Double, rx: Double, ry: Double) =
        "M${fmt(cx - rx)},${fmt(cy)} A${fmt(rx)},${fmt(ry)} 0 1,0 ${fmt(cx + rx)},${fmt(cy)} A${fmt(rx)},${fmt(ry)} 0 1,0 ${fmt(cx - rx)},${fmt(cy)} Z"

    private fun rect(x: Double, y: Double, w: Double, h: Double, rIn: Double): String {
        val r = minOf(rIn, w / 2, h / 2)
        if (r == 0.0) return "M${fmt(x)},${fmt(y)} H${fmt(x + w)} V${fmt(y + h)} H${fmt(x)} Z"
        val a = "A${fmt(r)},${fmt(r)} 0 0,1"
        return "M${fmt(x + r)},${fmt(y)} H${fmt(x + w - r)} $a ${fmt(x + w)},${fmt(y + r)} V${fmt(y + h - r)} " +
            "$a ${fmt(x + w - r)},${fmt(y + h)} H${fmt(x + r)} $a ${fmt(x)},${fmt(y + h - r)} V${fmt(y + r)} $a ${fmt(x + r)},${fmt(y)} Z"
    }

    /**
     * A mask that is the full viewport in white with black strokes on it: the viewport clockwise and each stroke's
     * outline counter-clockwise, so under the non-zero rule the strokes are holes in the clip.
     */
    private fun maskClip(name: String, mask: Element, w: Double, h: Double): String {
        val parts = mutableListOf<String>()
        for (i in 0 until mask.childNodes.length) {
            val el = mask.childNodes.item(i) as? Element ?: continue
            val fill = el.getAttribute("fill").lowercase()
            when {
                el.tagName == "rect" && fill in setOf("#fff", "#ffffff", "white") && d(el, "x") <= 0 && d(el, "y") <= 0 &&
                    d(el, "width") >= w && d(el, "height") >= h -> parts.add(0, "M0,0 H${fmt(w)} V${fmt(h)} H0 Z")
                el.tagName == "line" && el.getAttribute("stroke").lowercase() in inkColors ->
                    parts += capsule(d(el, "x1"), d(el, "y1"), d(el, "x2"), d(el, "y2"), d(el, "stroke-width") / 2,
                        el.getAttribute("stroke-linecap") == "round")
                else -> throw DisplayBuildException("$name: mask content <${el.tagName}> is not handled")
            }
        }
        if (!parts.first().startsWith("M0,0")) throw DisplayBuildException("$name: mask must start from the full viewport in white")
        return parts.joinToString(" ")
    }

    /** The outline of a stroked line, wound counter-clockwise on screen (y down). */
    fun capsule(x1: Double, y1: Double, x2: Double, y2: Double, h: Double, round: Boolean): String {
        val len = hypot(x2 - x1, y2 - y1)
        val ux = (x2 - x1) / len
        val uy = (y2 - y1) / len
        val nx = -uy
        val ny = ux
        // butt caps end at the points, round ones reach h past them
        val ax = x1 + nx * h; val ay = y1 + ny * h
        val bx = x2 + nx * h; val by = y2 + ny * h
        val cx = x2 - nx * h; val cy = y2 - ny * h
        val dx = x1 - nx * h; val dy = y1 - ny * h
        // A→B→C→D runs clockwise or not depending on the line's direction; pick the counter-clockwise order
        val area = (ax * by - bx * ay) + (bx * cy - cx * by) + (cx * dy - dx * cy) + (dx * ay - ax * dy)
        val pts = if (area < 0) listOf(ax to ay, bx to by, cx to cy, dx to dy) else listOf(dx to dy, cx to cy, bx to by, ax to ay)
        if (!round) return "M${p(pts[0])} L${p(pts[1])} L${p(pts[2])} L${p(pts[3])} Z"
        // the outline is convex and counter-clockwise, so are its caps: sweep flag 0 (1 is clockwise with y down)
        val arc = "A${fmt(h)},${fmt(h)} 0 0,0"
        return "M${p(pts[0])} L${p(pts[1])} $arc ${p(pts[2])} L${p(pts[3])} $arc ${p(pts[0])} Z"
    }

    private fun p(pt: Pair<Double, Double>) = "${fmt(pt.first)},${fmt(pt.second)}"

    fun fmt(v: Double): String {
        val r = Math.round(v * 1000) / 1000.0
        return if (abs(r - r.toLong()) < 1e-9) r.toLong().toString() else r.toString()
    }
}
